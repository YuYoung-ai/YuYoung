import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createWorkStore} from '../deno-auth/work-store.ts';
const source=fs.readFileSync(new URL('./work-kv.mjs',import.meta.url),'utf8');
const Kv=vm.runInNewContext(source.slice(source.indexOf('class Kv{'),source.indexOf('\nconst kv='))+'\nKv;', {structuredClone});
const kv=new Kv(),store=createWorkStore(kv),who={name:'CS',level:3};
await store.bridge('seed',{hospitals:[],references:{minimumLevel:1,engineers:[]}});
await store.bridge('activate',{manifest:await store.manifest()});
const request={id:'r1',revision:1,hospitalId:'h1',status:'완료'};
const pdf=n=>({kind:'inspection_pdf',url:'https://drive.google.com/file/d/file-'+n+'/view',filename:'report.pdf'});
await kv.set(['hospitalwork-v2','request','r1'],request);
const history=(id,at,attachment,extra={})=>kv.set(['hospitalwork-v2','history','r1',id],{id,kind:'comment',createdAt:at,attachment,...extra});
await history('old','2026-10-19T01:00:00Z',pdf('old'));
await history('new','2026-10-19T02:00:00Z',pdf('new'));
await history('deleted','2026-10-19T03:00:00Z',pdf('deleted'),{deletedAt:'now'});
await history('unsafe','2026-10-19T04:00:00Z',{kind:'inspection_pdf',url:'https://evil.example/file'});
await history('text','2026-10-19T05:00:00Z',null,{body:'나중에 등록한 일반 댓글'});
let scans=0;const list=kv.list.bind(kv);kv.list=(selector,options)=>{if(selector.prefix?.[1]==='history')scans++;return list(selector,options);};
const read=()=>store.handle({action:'work_inspection_links',requestIds:['r1','r1']},who);
let d=await read();assert.ok(d.success);assert.equal(d.items.length,1);assert.equal(d.items[0].attachment.url,pdf('new').url);assert.equal(scans,1);
assert.equal(d.items[0].payment,'unknown','no saved result is distinct from a result with blank cost');assert.deepEqual(d.items[0].resultItems,[]);
assert.equal(JSON.stringify(d).includes('일반 댓글'),false,'projection never returns comment/audit bodies');
await read();assert.equal(scans,1,'same revision reuses server projection without history scan');
await history('new','2026-10-19T02:00:00Z',pdf('new'),{deletedAt:'now'});
await kv.set(['hospitalwork-v2','request','r1'],{...request,revision:2});
d=await read();assert.equal(d.items[0].attachment.url,pdf('old').url,'deleted latest PDF falls back to preceding live PDF');
await history('old','2026-10-19T01:00:00Z',pdf('regen'),{updatedAt:'2026-10-19T06:00:00Z'});
await kv.set(['hospitalwork-v2','request','r1'],{...request,revision:3});
d=await read();assert.equal(d.items[0].attachment.url,pdf('regen').url,'regenerated PDF refreshes at request revision');
const result=(id,source,extra={})=>history(id,'2026-10-20',null,{kind:'result',source,...extra});
await result('result-1',{gubun:'A/S',cat:'핸드피스',type:'점검',cost:'무상',detail:'본문 비공개',sn:'A',date:'2026-10-20'});
await kv.set(['hospitalwork-v2','request','r1'],{...request,revision:10});
d=await read();assert.equal(d.items[0].payment,'free');assert.match(d.items[0].treatment,/A\/S \/ 핸드피스 \/ 점검/);assert.ok(!JSON.stringify(d).includes('본문 비공개'));
await result('result-2',{gubun:'A/S',cost:'165,000원',sn:'B'});
await kv.set(['hospitalwork-v2','request','r1'],{...request,revision:11});
d=await read();assert.equal(d.items[0].payment,'mixed');assert.deepEqual(d.items[0].resultItems.map(x=>x.payment).sort(),['free','paid'],'results retain separate payment decisions');
await result('result-2',{gubun:'A/S',cost:'',sn:'B'});
await kv.set(['hospitalwork-v2','request','r1'],{...request,revision:12,serviceOverrides:{asType:'무상'}});
d=await read();assert.equal(d.items[0].payment,'free','blank saved result cost is free');assert.deepEqual(d.items[0].resultItems.map(x=>x.payment),['free','free']);
await result('result-2',{gubun:'A/S',cost:'0',sn:'B'},{sourceReview:{pending:true}});
await kv.set(['hospitalwork-v2','request','r1'],{...request,revision:13});
d=await read();assert.equal(d.items[0].payment,'mixed');assert.deepEqual(d.items[0].resultItems.map(x=>x.payment).sort(),['free','unknown'],'pending result does not suppress another confirmed result');
await result('result-2',{gubun:'A/S',cost:'0',sn:'B'});
await kv.set(['hospitalwork-v2','request','r1'],{...request,revision:14});
assert.equal((await read()).items[0].payment,'free','explicit zero cost is distinct from a blank cost');
await kv.set(['hospitalwork-v2','inspectionLinks','r1'],{requestId:'r1',revision:14,attachment:null});
assert.equal((await read()).items[0].schema,3,'legacy projection is refreshed even at the same request revision');
await kv.set(['hospitalwork-v2','request','r1'],{...request,revision:4,purgedAt:'now'});
assert.equal((await read()).items[0].attachment,null,'purged receipt cannot expose previously cached link');
assert.equal((await store.handle({action:'work_inspection_links',requestIds:['r1']},{name:'outsider',level:0})).success,false);
for(const requestIds of [[],new Array(51).fill('r1'),['bad/id'],[{}]])assert.equal((await store.handle({action:'work_inspection_links',requestIds},who)).success,false);
console.log('work-inspection-links: live PDF selection, safe URL, revision cache, regeneration/deletion, purge visibility, access and batch bounds passed (modeled KV).');
