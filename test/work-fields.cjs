const assert=require('node:assert/strict'),fields=require('../js/baz-work-fields.js');
const a={key:'old',name:'원래 병원',sn:'SN1',asType:'유상',ncare:'가입'},r={hospitalKey:'old',sn:'SN1',visitAt:'2026-09-30T10:00',gubun:'점검'};
assert.equal(fields.hospital(r,[a]),a);
const renamed={...a,key:'new',name:'새 병원',asType:'무상'};
assert.equal(fields.hospital(r,[renamed]).name,'새 병원','unique exact serial recovers a renamed DB row');
assert.equal(fields.hospital({...r,sn:'historical-device',hospitalReferenceSN:'SN1'},[renamed]),renamed,'reference serial is independent of the historical device');
assert.equal(fields.hospital(r,[renamed,{...renamed,key:'other'}]),null,'ambiguous serials must not select a hospital');
assert.equal(fields.hospital({...r,sn:''},[renamed]),null,'no name fuzzy matching on DB disappearance');
assert.equal(fields.hospital(r,[{...a,origin:'flow'}]),null,'history rows never become DB candidates');
assert.equal(fields.terms(r,[renamed]).asType,'무상');
assert.equal(fields.terms({...r,serviceOverrides:{asType:'유상'}},[renamed]).asType,'유상');
assert.equal(fields.terms({...r,serviceOverrides:{}},[renamed]).asType,'무상');
assert.deepEqual(fields.range('week','2026-10-01','2026-10'),['2026-09-28','2026-10-04']);
assert.deepEqual(fields.range('lastweek','2026-10-01','2026-10'),['2026-09-21','2026-09-27']);
assert.deepEqual(fields.range('week','2026-01-01','2026-01'),['2025-12-29','2026-01-04']);
assert.deepEqual(fields.range('month','2024-02-01','2024-02'),['2024-02-01','2024-02-29']);
assert.ok(fields.matches(r,{gubun:['점검','A/S'],year:['2026'],month:['9'],quarter:['3'],asType:['무상']},[renamed]));
assert.ok(!fields.matches(r,{gubun:['A/S']},[renamed]));
assert.ok(!fields.matches(r,{year:['2026'],quarter:['4']},[renamed]));
console.log('work-fields: DB-only matching, rename by unique serial, ambiguity/missing serial, per-request override/reset, calendar Monday weeks across month/year, leap month and combined multi-select filters passed.');
